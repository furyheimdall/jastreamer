func testSOOD(properties ...[2]string) []byte {
	packet := []byte{'S', 'O', 'O', 'D', 2, 'R'}
	for _, property := range properties {
		packet = append(packet, byte(len(property[0])))
		packet = append(packet, property[0]...)
		packet = binary.BigEndian.AppendUint16(packet, uint16(len(property[1])))
		packet = append(packet, property[1]...)
	}
	return packet
}

func testSOODAdvert(tid, port string) []byte {
	return testSOOD([2]string{"service_id", soodServiceID}, [2]string{"_tid", tid}, [2]string{"tcp_port", port}, [2]string{"name", "Advertised output"})
}

func TestSOODParserRejectsMalformedPackets(t *testing.T) {
	valid := testSOOD([2]string{"key", "value"})
	cases := map[string][]byte{
		"short header":       valid[:5],
		"wrong magic":        []byte("NOOD\x02R"),
		"wrong version":      []byte("SOOD\x01R"),
		"wrong type":         []byte("SOOD\x02X"),
		"empty key":          append([]byte("SOOD\x02R"), 0, 0, 0),
		"truncated key":      append([]byte("SOOD\x02R"), 3, 'a'),
		"truncated length":   append([]byte("SOOD\x02R"), 1, 'a', 0),
		"truncated value":    valid[:len(valid)-1],
		"duplicate key":      testSOOD([2]string{"same", "one"}, [2]string{"same", "two"}),
		"NUL key":            testSOOD([2]string{"bad\x00key", "value"}),
		"NUL value":          testSOOD([2]string{"key", "bad\x00value"}),
		"invalid UTF8 key":   testSOOD([2]string{"\xff", "value"}),
		"invalid UTF8 value": testSOOD([2]string{"key", "\xff"}),
		"oversized packet":   testSOOD([2]string{"large", strings.Repeat("x", maxSOODPacket)}),
	}
	for name, packet := range cases {
		t.Run(name, func(t *testing.T) {
			if _, _, err := parseSOOD(packet); err == nil {
				t.Fatal("accepted malformed SOOD")
			}
		})
	}
}

func TestSOODNullEmptyAndMaximumPropertyCount(t *testing.T) {
	packet := testSOOD([2]string{"empty", ""})
	packet = append(packet, 4, 'n', 'u', 'l', 'l', 0xff, 0xff)
	kind, properties, err := parseSOOD(packet)
	if err != nil || kind != 'R' {
		t.Fatalf("null parse: %v", err)
	}
	if value, exists := properties["null"]; !exists || value != nil {
		t.Fatal("null property not retained")
	}
	if properties["empty"] == nil || *properties["empty"] != "" {
		t.Fatal("empty string confused with null")
	}
	packet = []byte("SOOD\x02R")
	for index := range maxSOODProperties {
		packet = append(packet, 3, 'k', byte('a'+index/26), byte('a'+index%26), 0, 0)
	}
	if _, properties, err := parseSOOD(packet); err != nil || len(properties) != maxSOODProperties {
		t.Fatalf("property boundary: %v", err)
	}
	packet = append(packet, 1, 'x', 0, 0)
	if _, _, err := parseSOOD(packet); err == nil {
		t.Fatal("unbounded property count")
	}
}

func TestSOODAcceptsUnsolicitedAdvertisement(t *testing.T) {
	network := localNetwork{local: netip.MustParseAddr("192.168.50.2"), prefix: netip.MustParsePrefix("192.168.50.0/24")}
	// This transaction ID was not generated by any query. Advertising must work
	// without a pending transaction, and its UDP source port is not a TCP port.
	packet := testSOODAdvert("22b62ef1-4803-4961-8b8b-be58d1c87a3c", "41015")
	advert, ok := advertisementFromSOOD(packet, netip.MustParseAddr("192.168.50.90"), network)
	if !ok {
		t.Fatal("valid unsolicited advertisement rejected")
	}
	if advert.endpoint.port != 41015 || advert.endpoint.address != "192.168.50.90" || advert.endpoint.localAddress != "192.168.50.2" {
		t.Fatalf("incorrect endpoint: %+v", advert.endpoint)
	}
	for _, address := range []string{"192.168.51.90", "8.8.8.8", "192.168.50.0", "192.168.50.255", "239.255.90.90", "::1"} {
		if _, ok := advertisementFromSOOD(packet, netip.MustParseAddr(address), network); ok {
			t.Fatalf("accepted off-subnet/non-host %s", address)
		}
	}
}

func TestSOODAdvertisementIdentityAndPortValidation(t *testing.T) {
	network := localNetwork{local: netip.MustParseAddr("10.2.3.4"), prefix: netip.MustParsePrefix("10.2.3.0/24")}
	source := netip.MustParseAddr("10.2.3.5")
	validTID := "22b62ef1-4803-4961-8b8b-be58d1c87a3c"
	for _, port := range []string{"", "0", "65536", "-1", "9003x"} {
		if _, ok := advertisementFromSOOD(testSOODAdvert(validTID, port), source, network); ok {
			t.Fatalf("accepted port %q", port)
		}
	}
	for _, tid := range []string{"", "not-a-uuid", "00000000-0000-0000-0000-000000000000"} {
		if _, ok := advertisementFromSOOD(testSOODAdvert(tid, "9003"), source, network); ok {
			t.Fatalf("accepted transaction %q", tid)
		}
	}
	packet := testSOOD([2]string{"service_id", "other-service"}, [2]string{"_tid", validTID}, [2]string{"tcp_port", "9003"})
	if _, ok := advertisementFromSOOD(packet, source, network); ok {
		t.Fatal("accepted unrelated service")
	}
	packet = testSOODAdvert(validTID, "9003")
	packet[5] = 'Q'
	if _, ok := advertisementFromSOOD(packet, source, network); ok {
		t.Fatal("accepted query as advertisement")
	}
}

func TestDiscoveryLANLimits(t *testing.T) {
	for _, raw := range []string{"10.1.2.3", "172.16.1.2", "192.168.1.2", "169.254.1.2", "127.0.0.1"} {
		if !allowedLocalAddress(netip.MustParseAddr(raw)) {
			t.Errorf("rejected LAN address %s", raw)
		}
	}
	for _, raw := range []string{"0.0.0.0", "8.8.8.8", "172.32.1.2", "239.255.90.90", "::1", "::ffff:192.168.1.2"} {
		if allowedLocalAddress(netip.MustParseAddr(raw)) {
			t.Errorf("accepted non-LAN IPv4 %s", raw)
		}
	}
	for _, raw := range []string{"0.0.0.0/0", "10.0.0.0/7", "172.0.0.0/8", "192.168.0.0/15"} {
		if allowedLocalPrefix(netip.MustParsePrefix(raw)) {
			t.Errorf("accepted excessively broad prefix %s", raw)
		}
	}
	if _, err := resolveNetworks([]string{" "}); err == nil {
		t.Fatal("accepted empty explicit interface")
	}
}

func TestDeviceInfoRequiresFreshUniqueIdentity(t *testing.T) {
	for _, raw := range []string{
		`{"status":"Failure","info":{"unique_id":"device"}}`,
		`{"status":"Success","info":{}}`,
		`{"status":"Success","info":{"unique_id":" "}}`,
		`{"status":"Success","info":{"unique_id":"bad\u0000id"}}`,
		`{"status":"Success","info":{"unique_id":17}}`,
		`{"status":"Success","info":{"unique_id":"device","protocol_version":3}}`,
	} {
		if _, err := parseDeviceInfo([]byte(raw)); err == nil {
			t.Fatalf("accepted invalid identity %s", raw)
		}
	}
	info, err := parseDeviceInfo([]byte(`{"status":"Success","info":{"unique_id":"vendor:stable","protocol_version":"unsupported","vendor":"Vendor","model":"Model","code_signing_keys":["key"]}}`))
	if err != nil {
		t.Fatal(err)
	}
	if info.uniqueID != "vendor:stable" || info.protocol != "unsupported" || string(info.codeSigningKeys) != `["key"]` {
		t.Fatalf("unsupported/signing-advertised device lost: %+v", info)
	}
}

func TestInspectAdvertisementUsesFreshInfoAndClosesWithoutScripts(t *testing.T) {
	listener, err := net.Listen("tcp4", "127.0.0.1:0")
	if err != nil {
		t.Fatal(err)
	}
	defer listener.Close()
	if err := listener.(*net.TCPListener).SetDeadline(time.Now().Add(3 * time.Second)); err != nil {
		t.Fatal(err)
	}
	serverResult := make(chan error, 1)
	go func() {
		conn, err := listener.Accept()
		if err != nil {
			serverResult <- err
			return
		}
		defer conn.Close()
		_ = conn.SetDeadline(time.Now().Add(3 * time.Second))
		kind, request, err := readControlFrame(conn)
		if err != nil {
			serverResult <- err
			return
		}
		if kind != managementRequest || len(request) < 4 || string(request[4:]) != `{"request":"get_info"}` {
			t.Error("discovery sent something other than get_info")
			serverResult <- io.ErrUnexpectedEOF
			return
		}
		id := binary.BigEndian.Uint32(request[:4])
		// An early nonfinal success is not valid identity evidence.
		err = writeControlBytes(conn, testControlResponse(managementResponse, id, 0, `{"status":"Success","info":{"unique_id":"stale"}}`))
		if err == nil {
			err = writeControlBytes(conn, testControlResponse(managementResponse, id, 1, `{"status":"Success","info":{"unique_id":"vendor:stable","protocol_version":"3","vendor":"Fresh vendor","model":"Fresh model","name":"Fresh name"}}`))
		}
		if err != nil {
			serverResult <- err
			return
		}
		var next [1]byte
		_, err = conn.Read(next[:])
		if err != io.EOF {
			t.Error("discovery failed to close or sent a script/keepalive")
			serverResult <- io.ErrUnexpectedEOF
			return
		}
		serverResult <- nil
	}()
	port := listener.Addr().(*net.TCPAddr).Port
	value, err := inspectAdvertisement(context.Background(), soodAdvertisement{endpoint: endpoint{address: "127.0.0.1", localAddress: "127.0.0.1", port: port}, name: "Stale advertised name"})
	if err != nil {
		t.Fatal(err)
	}
	hash := sha256.Sum256([]byte("vendor:stable"))
	if value.device.ID != "raat:"+hex.EncodeToString(hash[:]) || value.device.Name != "Fresh name" || value.device.Manufacturer != "Fresh vendor" || value.device.Model != "Fresh model" {
		t.Fatalf("fresh identity not used: %+v", value.device)
	}
	if !value.device.Online || value.device.LastSeen == "" || value.device.LocalAddress != "127.0.0.1" || !value.device.Capabilities.Play || !value.device.Capabilities.Pause || !value.device.Capabilities.Stop || !value.device.Capabilities.Seek {
		t.Fatalf("incomplete discovery device: %+v", value.device)
	}
	if err := <-serverResult; err != nil {
		t.Fatal(err)
	}
}
